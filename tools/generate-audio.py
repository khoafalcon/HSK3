"""Generate bundled Mandarin WAV files; not needed to run the miniapp.

Requires piper-tts==1.8.0 and a Piper Mandarin voice model.
Input JSON is an array of objects with a `text` field (exported from VOCAB).
"""
import argparse
import hashlib
import json
import wave
from pathlib import Path

import numpy as np
from piper import PiperVoice, SynthesisConfig

parser = argparse.ArgumentParser()
parser.add_argument('--model', required=True)
parser.add_argument('--words', required=True)
args = parser.parse_args()
root = Path(__file__).resolve().parents[1]
output = root / 'assets' / 'audio'
output.mkdir(parents=True, exist_ok=True)
words = json.loads(Path(args.words).read_text(encoding='utf-8'))
texts = list(dict.fromkeys(word['text'] for word in words))
voice = PiperVoice.load(args.model)
config = SynthesisConfig(length_scale=1.12, volume=0.9)
manifest = {}
durations = []
for index, text in enumerate(texts, 1):
    filename = hashlib.sha256(text.encode('utf-8')).hexdigest()[:16] + '.wav'
    target = output / filename
    if not target.exists():
        temporary = target.with_suffix('.tmp.wav')
        with wave.open(str(temporary), 'wb') as wav:
            voice.synthesize_wav(text if text[-1] in '。！？' else text + '\u3002', wav, syn_config=config)
        temporary.replace(target)
    with wave.open(str(target), 'rb') as wav:
        duration = wav.getnframes() / wav.getframerate()
        samples = np.frombuffer(wav.readframes(wav.getnframes()), dtype=np.int16).astype(float)
        rms = float(np.sqrt(np.mean(samples * samples)))
        assert wav.getnchannels() == 1 and wav.getsampwidth() == 2
        assert 0.15 < duration < 60 and rms > 100, (text, duration, rms)
    durations.append(duration)
    manifest[text] = 'assets/audio/' + filename
    if index % 25 == 0 or index == len(texts):
        print(f'Generated and verified {index}/{len(texts)} clips', flush=True)
(root / 'assets' / 'js' / 'audio-map.js').write_text(
    '// Generated by tools/generate-audio.py; bundled Mandarin audio.\n'
    + 'const VOCAB_AUDIO = ' + json.dumps(manifest, ensure_ascii=False, indent=2) + ';\n',
    encoding='utf-8')
print(json.dumps({'entries': len(words), 'clips': len(manifest), 'seconds': round(sum(durations), 2),
                  'bytes': sum((output / Path(path).name).stat().st_size for path in manifest.values())}), flush=True)
